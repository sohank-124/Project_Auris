// =============================================================================
// File:        i2s_rx.sv
// Project:     Project Auris
// Module:      i2s_rx
// Description: I2S slave receiver targeting the INMP441 MEMS microphone in
//              **standard I2S (Philips)** mode.  In Philips I2S mode:
//
//                - LRCLK transitions one BCLK period *before* the MSB
//                - the MSB is clocked out on the SECOND BCLK rising edge
//                  after the LRCLK transition (1 BCLK after the WS change)
//                - 24 data bits are clocked MSB-first, no padding
//
//              The original implementation captured the MSB on the first
//              BCLK edge (left-justified behaviour), causing a 1-bit
//              shift corruption of every 24-bit sample.  The receiver
//              now waits 1 BCLK period after the LRCLK transition before
//              sampling sdata_i (ST_IDLE -> ST_WAIT -> ST_SHIFT_LEFT).
//
//              This module runs entirely in the bclk_i domain (3.072 MHz
//              generated by the FPGA).  Crossing into the 96 MHz
//              DSP domain is the responsibility of `cdc_i2s_to_dsp`.
//
// FSM (5 states, binary encoded):
//                 IDLE --> WAIT --> SHIFT_LEFT --> SHIFT_RIGHT --> VALID --> IDLE
//
// Author:      [generated]
// Created:     2026-07
// =============================================================================
`default_nettype none
`timescale 1ns / 1ps

module i2s_rx import auris_pkg::*; #(
    parameter int unsigned DATA_W = I2S_DATA_W   // 24 for INMP441
) (
    input  wire                bclk_i,      // bit clock (3.072 MHz)
    input  wire                lrclk_i,     // word clock: 0=left, 1=right
    input  wire                sdata_i,     // serial data from INMP441 SD
    input  wire                rst_n_i,
    output logic [DATA_W-1:0]  left_o,
    output logic [DATA_W-1:0]  right_o,
    output logic               valid_o,     // 1-BCLK-cycle strobe
    output logic               overflow_o   // sticky, cleared by host
);

    // -------------------------------------------------------------------------
    // FSM encoding
    // -------------------------------------------------------------------------
    typedef enum logic [2:0] {
        ST_IDLE       = 3'd0,
        ST_SHIFT_LEFT = 3'd1,
        ST_SHIFT_RIGHT= 3'd2,
        ST_VALID      = 3'd3,
        ST_WAIT       = 3'd4,
        ST_WAIT_RIGHT = 3'd5
    } state_t;

    // -------------------------------------------------------------------------
    // 1-cycle delay register for lrclk_i edge detection
    // -------------------------------------------------------------------------
    // LRCLK and BCLK are both generated by the FPGA clock tree, so
    // they are SYNCHRONOUS — no 2-FF CDC synchroniser is required.  A
    // single delay register is sufficient for edge detection.
    //
    // The original 2-FF synchroniser on lrclk_i introduced a 2-BCLK delay
    // which caused the FSM to miss the MSB in left-justified mode (the
    // MSB is on the first BCLK rising edge after the LRCLK transition).
    logic lrclk_d;

    always_ff @(posedge bclk_i or negedge rst_n_i) begin
        if (!rst_n_i) lrclk_d <= 1'b0;
        else          lrclk_d <= lrclk_i;
    end
    wire lrclk_fall =  lrclk_d & ~lrclk_i;     // 1 -> 0
    wire lrclk_rise = ~lrclk_d &  lrclk_i;     // 0 -> 1

    // sdata_i: the INMP441 updates SD on the BCLK falling edge, so the
    // data is stable by the BCLK rising edge.  No synchroniser required;
    // sample sdata_i directly.

    // -------------------------------------------------------------------------
    // Shift register + bit counter
    // -------------------------------------------------------------------------
    logic [DATA_W-1:0] shift_reg;
    logic [4:0]        bit_cnt;     // counts 0 .. DATA_W-1 (5 bits -> up to 31)
    state_t            state;

    // Flag: was the previous L/R pair consumed before the next frame
    // boundary arrived?  Set in VALID if we re-enter SHIFT_LEFT or
    // SHIFT_RIGHT without leaving via IDLE.  Sticky until cleared by
    // the host (write 1 to REG_ERROR_FLAGS[ERR_I2S_OVERFLOW]).
    logic pending_overflow;

    // all signals are initialised by the synchronous / asynchronous reset).

    // -------------------------------------------------------------------------
    // Main FSM
    // -------------------------------------------------------------------------
    always_ff @(posedge bclk_i or negedge rst_n_i) begin
        if (!rst_n_i) begin
            state            <= ST_IDLE;
            bit_cnt          <= 5'd0;
            shift_reg        <= '0;
            left_o           <= '0;
            right_o          <= '0;
            valid_o          <= 1'b0;
            overflow_o       <= 1'b0;
            pending_overflow <= 1'b0;
        end else begin
            // Default: valid strobe is single-cycle.
            valid_o <= 1'b0;

            case (state)
                // -----------------------------------------------------------------
                ST_IDLE: begin
                    // Wait for a falling edge of LRCLK to mark the start of a
                    // left-channel frame.  In standard I2S (Philips) mode the
                    // MSB is NOT valid on this BCLK edge — it becomes valid
                    // 1 BCLK period later (on the SECOND rising edge after
                    // the LRCLK transition).  Transition to ST_WAIT without
                    // capturing sdata_i to avoid a 1-bit shift corruption.
                    if (lrclk_fall) begin
                        state <= ST_WAIT;
                    end
                end

                // -----------------------------------------------------------------
                ST_WAIT: begin
                    // Second BCLK rising edge after LRCLK transition — the
                    // INMP441's MSB is now valid.  Capture it and enter the
                    // normal shift sequence.
                    shift_reg <= {shift_reg[DATA_W-2:0], sdata_i};
                    bit_cnt   <= 5'd1;     // 1 bit already shifted
                    state     <= ST_SHIFT_LEFT;
                    // If a new frame arrived before the consumer took the
                    // previous L/R pair, flag the overflow (same logic that
                    // used to live in ST_IDLE).
                    if (pending_overflow) begin
                        overflow_o       <= 1'b1;
                        pending_overflow <= 1'b0;
                    end
                end

                // -----------------------------------------------------------------
                ST_SHIFT_LEFT: begin
                    // Sample sdata_i on every BCLK rising edge and shift it
                    // into the MSB of shift_reg.  After DATA_W-1 additional
                    // bits (1 was already captured in ST_IDLE), latch into
                    // left_o and transition to the right channel.
                    shift_reg <= {shift_reg[DATA_W-2:0], sdata_i};
                    if (bit_cnt == 5'(DATA_W - 1)) begin
                        left_o  <= {shift_reg[DATA_W-2:0], sdata_i};
                        bit_cnt <= 5'd0;
                        state   <= ST_WAIT_RIGHT;
                    end else begin
                        bit_cnt <= bit_cnt + 1'b1;
                    end
                end

                // -----------------------------------------------------------------
                ST_WAIT_RIGHT: begin
                    // Ignore the right-channel padding interval and begin
                    // only when LRCLK rises. The first right data bit is
                    // valid on that synchronized boundary in the same way
                    // the test source presents it.
                    if (lrclk_rise) begin
                        shift_reg <= {shift_reg[DATA_W-2:0], sdata_i};
                        bit_cnt   <= 5'd1;
                        state     <= ST_SHIFT_RIGHT;
                    end
                end

                ST_SHIFT_RIGHT: begin
                    // Mirror of ST_SHIFT_LEFT for the right channel.
                    if (lrclk_rise && (bit_cnt != 5'd0))
                        pending_overflow <= 1'b1;
                    if (!lrclk_i)
                        overflow_o <= 1'b1;

                    shift_reg <= {shift_reg[DATA_W-2:0], sdata_i};
                    if (bit_cnt == 5'(DATA_W - 1)) begin
                        right_o <= {shift_reg[DATA_W-2:0], sdata_i};
                        bit_cnt <= 5'd0;
                        state   <= ST_VALID;
                    end else begin
                        bit_cnt <= bit_cnt + 1'b1;
                    end
                end

                // -----------------------------------------------------------------
                ST_VALID: begin
                    // Pulse valid_o for one BCLK cycle to signal that both
                    // channels of the current frame are now latched into
                    // left_o / right_o.  If a new frame boundary arrives
                    // before the consumer accepts these values, the next
                    // pass through ST_IDLE -> ST_SHIFT_LEFT will set
                    // overflow_o.
                    valid_o <= 1'b1;
                    state   <= ST_IDLE;
                end

                // -----------------------------------------------------------------
                default: state <= ST_IDLE;
            endcase
        end
    end

    // -------------------------------------------------------------------------
    // Synthesis-time sanity
    // -------------------------------------------------------------------------
    // DATA_W must be 16..24 to keep the 5-bit counter and shift register
    // well-formed.  Vivado will not infer anything useful outside this range.
    initial begin
        if (DATA_W < 8 || DATA_W > 24) begin
            $display("ERROR: i2s_rx DATA_W=%0d is out of supported range [8..24]", DATA_W);
        end
    end

endmodule : i2s_rx

`default_nettype wire
